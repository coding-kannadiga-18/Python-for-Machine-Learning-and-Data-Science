# Important String Methods

name = "Coding Kannadiga"                       # n => 4, 8, 9
print(name.upper())                             # converts string into Upper Case
print(name.lower())                             # converts string into Lower Case

print(name.strip(" ,#"))                        # Remove extra spaces in starting and ending
print(name.replace("Coding","Code"))            # Replace character or word in a string

print(name.split("a"))                          # Divides string
print(name.find("n"))                           # returns position of a character
print(name.count("Co"))                         # returns frequency of a character

